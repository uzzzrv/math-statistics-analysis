# Функция распределения показательного закона
def F_theor(x):
    if x < 0:
        return 0.0
    return 1.0 - np.exp(-lambda_exp * x)

D_N = 0.0
y_star = None
F_y_star = None
F_N_y_star = None
F_N_y_star_minus_0 = None

for j in range(1, N + 1):
    yj = y_sorted[j - 1]

    # Эмпирическая функция распределения
    F_N_yj = j / N
    F_N_yj_minus_0 = (j - 1) / N

    # Теоретическая функция распределения
    F_yj = F_theor(yj)

    diff1 = abs(F_N_yj - F_yj)
    diff2 = abs(F_N_yj_minus_0 - F_yj)
    current_max = max(diff1, diff2)

    if current_max > D_N:
        D_N = current_max
        y_star = yj
        F_y_star = F_yj
        F_N_y_star = F_N_yj
        F_N_y_star_minus_0 = F_N_yj_minus_0

